export const dictionaries: Record<Locale, Messages> = { es, en };

export function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

function lookupIn(messages: Messages, key: string): string | undefined {
  const parts = key.split('.');
  let cur: unknown = messages;
  for (const part of parts) {
    if (cur === null || typeof cur !== 'object' || !(part in (cur as object))) return undefined;
    cur = (cur as Record<string, unknown>)[part];
  }
  return typeof cur === 'string' ? cur : undefined;
}

/**
 * Locale-aware translate for non-React modules (errors thrown in lib code).
 * Reads the same fc_lang localStorage/cookie the I18nContext uses; ES by default.
 */
export function tClient(key: string, vars?: Record<string, string | number>): string {
  let locale: Locale = 'es';
  if (typeof window !== 'undefined') {
    const saved = window.localStorage.getItem('fc_lang');
    const cookie = document.cookie.match(/(?:^|; )fc_lang=(\w+)/)?.[1];
    if (saved === 'en' || saved === 'es') locale = saved;
    else if (cookie === 'en' || cookie === 'es') locale = cookie;
  }
  return interpolate(lookupIn(dictionaries[locale], key) ?? key, vars);
}
